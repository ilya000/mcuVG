#!/usr/bin/env python3
"""mcuVG bench - the bench's pictures as C arrays (icons.h) and the host's checksums of what they draw
(expect.h), so the M33 run proves it draws the same pixels.  Run by run.sh."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
import svgfront  # noqa: E402
import vg_host  # noqa: E402
import mcuvg  # noqa: E402

T = os.path.join(HERE, "..", "..", "tests", "svg")
PICS = [
    ("evenodd", os.path.join(T, "opacity_evenodd.svg")),
    ("arcs", os.path.join(T, "arcs_transform.svg")),
    ("css", os.path.join(T, "rgba_css.svg")),
    ("strokes", os.path.join(T, "strokes.svg")),
    ("gradient", os.path.join(T, "grad_linear.svg")),
    ("radial", os.path.join(T, "grad_radial.svg")),
]
T2 = os.path.join(HERE, "..", "..", "tests", "svg2")
PICS2 = [(n, os.path.join(T2, n + ".svg")) for n in ("shadow", "glow", "blur", "clip", "opacity", "dash", "grad")]   # version 2
SIZES = [112, 240, 480]


def fnv(b):
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


lib = vg_host.Lib(extra=["-ffp-contract=off"])
with open(os.path.join(HERE, "out", "icons.h"), "w") as f, open(os.path.join(HERE, "out", "expect.h"), "w") as g:
    f.write("/* generated by gen_icons.py */\n")
    names = []
    for v2, pics in ((0, PICS), (1, PICS2)):
        if v2:
            f.write("#if MCUVG_V2\n")
        for name, path in pics:
            doc = svgfront.load(path)
            b = mcuvg.encode(doc, 480)
            f.write(f"static const uint8_t pic_{name}[{len(b)}] __attribute__((aligned(4), section(\".rodata.pics\"))) = {{" + ",".join(str(x) for x in b) + "};\n")
            names.append((name, len(b), doc.vb[2], v2))
            for size in SIZES:
                raw, rc = lib.draw_mcuvg(b, size, size, size / doc.vb[2], fmt=vg_host.RGB565)
                assert rc == 0, (name, size, rc)
                g.write(f"#define EXPECT_{name}_{size} 0x{fnv(raw):08X}u\n")
        if v2:
            f.write("#endif\n")
    f.write("static const struct pic { const char *name; const uint8_t *b; uint32_t len; float w; uint32_t expect[3]; } s_pics[] = {\n")
    for v2 in (0, 1):
        if v2:
            f.write("#if MCUVG_V2\n")
        for name, n, w, vv in names:
            if vv == v2:
                f.write(f'    {{ "{name}", pic_{name}, {n}u, {w}f, {{ ' + ", ".join(f"EXPECT_{name}_{s}" for s in SIZES) + " } },\n")
        if v2:
            f.write("#endif\n")
    f.write("};\n")
print("icons:", ", ".join(f"{n} {b} B" for n, b, _w, _v in names))
